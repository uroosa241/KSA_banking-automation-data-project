
CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE IF NOT EXISTS audit.pipeline_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    pipeline_name VARCHAR(150) NOT NULL,

    run_status VARCHAR(30) NOT NULL,

    started_at TIMESTAMP NOT NULL,

    completed_at TIMESTAMP,

    records_loaded BIGINT DEFAULT 0,

    error_message TEXT,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_run_status
        CHECK (
            run_status IN (
                'RUNNING',
                'SUCCESS',
                'FAILED'
            )
        )
);

CREATE INDEX IF NOT EXISTS idx_pipeline_runs_name
ON audit.pipeline_runs(pipeline_name);

CREATE INDEX IF NOT EXISTS idx_pipeline_runs_status
ON audit.pipeline_runs(run_status);
