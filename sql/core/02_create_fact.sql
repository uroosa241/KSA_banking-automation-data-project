
CREATE TABLE IF NOT EXISTS core.fact_transactions (
    transaction_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(30) UNIQUE NOT NULL,

    customer_key BIGINT
        REFERENCES core.dim_customer(customer_key),

    account_key BIGINT
        REFERENCES core.dim_account(account_key),

    branch_key BIGINT
        REFERENCES core.dim_branch(branch_key),

    date_key INTEGER
        REFERENCES core.dim_date(date_key),

    transaction_type VARCHAR(30),
    amount NUMERIC(18,2),
    currency VARCHAR(10),
    transaction_date TIMESTAMP,
    transaction_status VARCHAR(30),

    loaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_fact_customer
ON core.fact_transactions(customer_key);

CREATE INDEX IF NOT EXISTS idx_fact_account
ON core.fact_transactions(account_key);

CREATE INDEX IF NOT EXISTS idx_fact_branch
ON core.fact_transactions(branch_key);

CREATE INDEX IF NOT EXISTS idx_fact_date
ON core.fact_transactions(date_key);

CREATE INDEX IF NOT EXISTS idx_fact_transaction_date
ON core.fact_transactions(transaction_date);
    