
CREATE SCHEMA IF NOT EXISTS core;

-- 1. Customer Dimension
CREATE TABLE IF NOT EXISTS core.dim_customer (
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(20) UNIQUE NOT NULL,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(255),
    phone VARCHAR(100),
    city VARCHAR(100),
    gender VARCHAR(20),
    date_of_birth DATE,
    registration_date DATE
);

-- 2. Account Dimension
CREATE TABLE IF NOT EXISTS core.dim_account (
    account_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id VARCHAR(30) UNIQUE NOT NULL,
    customer_key BIGINT REFERENCES core.dim_customer(customer_key),
    account_type VARCHAR(30),
    iban VARCHAR(40),
    balance NUMERIC(18,2),
    currency VARCHAR(10),
    account_status VARCHAR(30),
    opening_date DATE
);

-- 3. Branch Dimension
CREATE TABLE IF NOT EXISTS core.dim_branch (
    branch_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id VARCHAR(20) UNIQUE NOT NULL,
    branch_name VARCHAR(100)
);

-- 4. Date Dimension
CREATE TABLE IF NOT EXISTS core.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE UNIQUE NOT NULL,
    day_number INTEGER,
    month_number INTEGER,
    month_name VARCHAR(20),
    quarter_number INTEGER,
    year_number INTEGER,
    day_name VARCHAR(20),
    is_weekend BOOLEAN
);
