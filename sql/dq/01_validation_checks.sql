
CREATE SCHEMA IF NOT EXISTS dq;

CREATE TABLE IF NOT EXISTS dq.validation_results (
    check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_name VARCHAR(150),
    checked_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    failed_count BIGINT,
    severity VARCHAR(20),
    details TEXT
);

INSERT INTO dq.validation_results (
    check_name,
    failed_count,
    severity,
    details
)

SELECT
    'Duplicate customer IDs in raw data',
    COUNT(*),
    'HIGH',
    'Checks duplicate customer IDs in raw customers'
FROM (
    SELECT customer_id
    FROM raw.customers
    GROUP BY customer_id
    HAVING COUNT(*) > 1
) duplicates

UNION ALL

SELECT
    'Duplicate account IDs in raw data',
    COUNT(*),
    'HIGH',
    'Checks duplicate account IDs in raw accounts'
FROM (
    SELECT account_id
    FROM raw.accounts
    GROUP BY account_id
    HAVING COUNT(*) > 1
) duplicates

UNION ALL

SELECT
    'Duplicate transaction IDs in raw data',
    COUNT(*),
    'HIGH',
    'Checks duplicate transaction IDs in raw transactions'
FROM (
    SELECT transaction_id
    FROM raw.transactions
    GROUP BY transaction_id
    HAVING COUNT(*) > 1
) duplicates

UNION ALL

SELECT
    'Accounts without matching customers',
    COUNT(*),
    'HIGH',
    'Accounts whose customer ID does not exist in staging customers'
FROM staging.accounts a
LEFT JOIN staging.customers c
    ON a.customer_id = c.customer_id
WHERE c.customer_id IS NULL

UNION ALL

SELECT
    'Transactions without matching accounts',
    COUNT(*),
    'HIGH',
    'Transactions whose account ID does not exist in staging accounts'
FROM staging.transactions t
LEFT JOIN staging.accounts a
    ON t.account_id = a.account_id
WHERE a.account_id IS NULL

UNION ALL

SELECT
    'Transactions without matching customers',
    COUNT(*),
    'HIGH',
    'Transactions whose customer ID does not exist in staging customers'
FROM staging.transactions t
LEFT JOIN staging.customers c
    ON t.customer_id = c.customer_id
WHERE c.customer_id IS NULL

UNION ALL

SELECT
    'Transaction and account customer mismatch',
    COUNT(*),
    'HIGH',
    'Transaction customer ID differs from the account owner customer ID'
FROM staging.transactions t
JOIN staging.accounts a
    ON t.account_id = a.account_id
WHERE t.customer_id <> a.customer_id
   OR t.customer_id IS NULL

UNION ALL

SELECT
    'Transactions with missing amounts',
    COUNT(*),
    'HIGH',
    'Checks transactions where amount is NULL'
FROM staging.transactions
WHERE amount IS NULL

UNION ALL

SELECT
    'Transactions with negative amounts',
    COUNT(*),
    'MEDIUM',
    'Negative amounts require investigation'
FROM staging.transactions
WHERE amount < 0;
